import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  CreateDateColumn,
  UpdateDateColumn,
  ManyToOne,
  JoinColumn,
  OneToMany,
} from 'typeorm';
import { ApiProperty } from '@nestjs/swagger';
import { BranchCatalogScope } from '../../../common/enums/branch-catalog-scope.enum';
import { Product } from '../../products/entities/product.entity';
import { RecipeIngredient } from './recipe-ingredient.entity';

@Entity()
export class Recipe {
  @ApiProperty({ example: 1 })
  @PrimaryGeneratedColumn()
  id: number;

  @ApiProperty({ example: 'Mutura Large Batch' })
  @Column({ unique: true })
  name: string;

  @ApiProperty({ enum: BranchCatalogScope, example: BranchCatalogScope.GENERAL_BUTCHERY })
  @Column({
    type: 'enum',
    enum: BranchCatalogScope,
    default: BranchCatalogScope.GENERAL_BUTCHERY,
  })
  branchScope: BranchCatalogScope;

  @ApiProperty({ description: 'Finished product generated by this recipe', example: 1 })
  @ManyToOne(() => Product, { eager: true })
  @JoinColumn({ name: 'finishedProductId' })
  finishedProduct: Product;

  @ApiProperty({ example: 1 })
  @Column()
  finishedProductId: number;

  @ApiProperty({ description: 'Expected output quantity from one run', example: 40 })
  @Column('decimal', { precision: 10, scale: 2 })
  expectedOutputQuantity: number;

  @ApiProperty({ description: 'Output unit', example: 'portion' })
  @Column()
  outputUnit: string;

  @ApiProperty({ description: 'Optional notes', required: false })
  @Column({ type: 'text', nullable: true })
  notes: string | null;

  @ApiProperty({ example: true })
  @Column({ default: true })
  isActive: boolean;

  @CreateDateColumn()
  createdAt: Date;

  @UpdateDateColumn()
  updatedAt: Date;

  @OneToMany(() => RecipeIngredient, (ingredient) => ingredient.recipe, {
    cascade: true,
    eager: true,
  })
  ingredients: RecipeIngredient[];
}
